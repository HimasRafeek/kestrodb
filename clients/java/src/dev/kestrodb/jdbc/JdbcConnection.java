package dev.kestrodb.jdbc;

import dev.kestrodb.KestroClient;
import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;
import java.sql.SQLFeatureNotSupportedException;
import java.sql.SQLNonTransientConnectionException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.Collections;
import java.util.Locale;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

/**
 * java.sql.Connection over one {@link KestroClient}. Auto-commit is on by default (each
 * statement commits alone). With it off, the first statement opens a transaction (BEGIN) that
 * commit() or rollback() ends; DDL never opens one. KestroDB transactions hold the write gate
 * until they end, so keep them short.
 */
final class JdbcConnection implements Jdbc.Unwrappable {
    final KestroClient db;
    final String url;
    Connection self;
    private boolean autoCommit = true;
    private boolean closed;
    private final Properties clientInfo = new Properties();

    private JdbcConnection(KestroClient db, String url) {
        this.db = db;
        this.url = url;
    }

    static Connection create(KestroClient db, String url) {
        JdbcConnection c = new JdbcConnection(db, url);
        c.self = Jdbc.wrap(Connection.class, c);
        return c.self;
    }

    @Override public Object inner() { return db; }

    void check() throws SQLException {
        if (closed) throw new SQLNonTransientConnectionException("CLOSED the connection was closed", "08003");
    }

    /** With auto-commit off: BEGIN before the first statement of a transaction. */
    void implicitBegin(String sql) {
        if (autoCommit || db.inTransaction()) return;
        String head = sql.stripLeading();
        int end = 0;
        while (end < head.length() && Character.isLetter(head.charAt(end))) end++;
        switch (head.substring(0, end).toUpperCase(Locale.ROOT)) {
            case "BEGIN": case "START": case "COMMIT": case "ROLLBACK": case "END": case "SAVEPOINT": case "RELEASE":
            case "CREATE": case "DROP": case "ALTER":
                return;
            default:
                db.begin();
        }
    }

    public Statement createStatement() throws SQLException {
        check();
        return JdbcStatement.create(this, null);
    }

    public Statement createStatement(int type, int concurrency) throws SQLException {
        checkCursor(type, concurrency);
        return createStatement();
    }

    public Statement createStatement(int type, int concurrency, int holdability) throws SQLException {
        checkCursor(type, concurrency);
        return createStatement();
    }

    public PreparedStatement prepareStatement(String sql) throws SQLException {
        check();
        if (sql == null) throw new SQLException("sql is null", "42000");
        return (PreparedStatement) JdbcStatement.create(this, sql);
    }

    public PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException { return prepareStatement(sql); }

    public PreparedStatement prepareStatement(String sql, int[] columnIndexes) throws SQLException { return prepareStatement(sql); }

    public PreparedStatement prepareStatement(String sql, String[] columnNames) throws SQLException { return prepareStatement(sql); }

    public PreparedStatement prepareStatement(String sql, int type, int concurrency) throws SQLException {
        checkCursor(type, concurrency);
        return prepareStatement(sql);
    }

    public PreparedStatement prepareStatement(String sql, int type, int concurrency, int holdability) throws SQLException {
        checkCursor(type, concurrency);
        return prepareStatement(sql);
    }

    private static void checkCursor(int type, int concurrency) throws SQLException {
        if (type == ResultSet.TYPE_SCROLL_SENSITIVE || concurrency != ResultSet.CONCUR_READ_ONLY)
            throw new SQLFeatureNotSupportedException("only read-only, forward-only or scroll-insensitive result sets");
    }

    public String nativeSQL(String sql) { return sql; }

    public void setAutoCommit(boolean on) throws SQLException {
        check();
        if (on && !autoCommit && db.inTransaction()) db.commit();   // JDBC: switching it on commits
        autoCommit = on;
    }

    public boolean getAutoCommit() throws SQLException { check(); return autoCommit; }

    public void commit() throws SQLException { check(); db.commit(); }

    public void rollback() throws SQLException { check(); db.rollback(); }

    public void close() {
        if (closed) return;
        closed = true;
        db.close();
    }

    public boolean isClosed() { return closed; }

    public boolean isValid(int timeoutSeconds) throws SQLException {
        if (timeoutSeconds < 0) throw new SQLException("timeout < 0");
        if (closed) return false;
        try {
            db.stats();
            return true;
        } catch (RuntimeException e) {
            return false;
        }
    }

    public DatabaseMetaData getMetaData() throws SQLException {
        check();
        return Jdbc.wrap(DatabaseMetaData.class, new JdbcDatabaseMetaData(this));
    }

    public void setReadOnly(boolean readOnly) throws SQLException { check(); }

    public boolean isReadOnly() throws SQLException { check(); return false; }

    public void setCatalog(String catalog) throws SQLException { check(); }

    public String getCatalog() throws SQLException { check(); return null; }

    public void setSchema(String schema) throws SQLException { check(); }

    public String getSchema() throws SQLException { check(); return null; }

    /** BEGIN transactions are serializable: one writes at a time and reads a snapshot. */
    public void setTransactionIsolation(int level) throws SQLException { check(); }

    public int getTransactionIsolation() throws SQLException { check(); return Connection.TRANSACTION_SERIALIZABLE; }

    public SQLWarning getWarnings() throws SQLException { check(); return null; }

    public void clearWarnings() throws SQLException { check(); }

    public void setHoldability(int holdability) throws SQLException { check(); }

    /** Results are read whole, so they stay usable after COMMIT. */
    public int getHoldability() throws SQLException { check(); return ResultSet.HOLD_CURSORS_OVER_COMMIT; }

    public Map<String, Class<?>> getTypeMap() throws SQLException { check(); return Collections.emptyMap(); }

    public void setClientInfo(String name, String value) throws SQLClientInfoException {
        if (value == null) clientInfo.remove(name);
        else clientInfo.setProperty(name, value);
    }

    public void setClientInfo(Properties properties) throws SQLClientInfoException {
        clientInfo.clear();
        if (properties != null) clientInfo.putAll(properties);
    }

    public String getClientInfo(String name) { return clientInfo.getProperty(name); }

    public Properties getClientInfo() {
        Properties p = new Properties();
        p.putAll(clientInfo);
        return p;
    }

    public void abort(Executor executor) { close(); }

    public void setNetworkTimeout(Executor executor, int milliseconds) throws SQLException {
        throw new SQLFeatureNotSupportedException("set the timeout in the URL or Properties (timeout=seconds)");
    }

    public int getNetworkTimeout() { return 0; }

    @Override public String toString() { return "KestroDB " + db.address(); }
}
