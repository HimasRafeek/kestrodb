package dev.kestrodb.jdbc;

import dev.kestrodb.KestroClient;
import dev.kestrodb.KestroException;
import dev.kestrodb.SqlResult;
import java.math.BigDecimal;
import java.sql.BatchUpdateException;
import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.ResultSetMetaData;
import java.sql.SQLException;
import java.sql.SQLFeatureNotSupportedException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.sql.Time;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.Calendar;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * java.sql.Statement and PreparedStatement. Parameters are positional ({@code ?}, {@code ?N},
 * {@code $N}); setObject takes any value {@link dev.kestrodb.Json} can write (Map and List are
 * stored as JSON). Results are read whole.
 */
final class JdbcStatement implements Jdbc.Unwrappable {
    private static final Object UNSET = new Object();

    private final JdbcConnection conn;
    private final String sql;            // null: a plain Statement
    private Statement self;
    private final List<Object> params = new ArrayList<>();
    private final List<Object> batch = new ArrayList<>();   // SQL strings, or parameter lists
    private ResultSet resultSet;
    private long updateCount = -1;
    private Object lastInsertId;
    private long maxRows;
    private int queryTimeout;
    private int fetchSize;
    private boolean closed;
    private boolean closeOnCompletion;
    private boolean poolable;

    private JdbcStatement(JdbcConnection conn, String sql) {
        this.conn = conn;
        this.sql = sql;
    }

    static Statement create(JdbcConnection conn, String sql) {
        JdbcStatement s = new JdbcStatement(conn, sql);
        s.self = sql == null ? Jdbc.wrap(Statement.class, s) : Jdbc.wrap(PreparedStatement.class, s);
        return s.self;
    }

    @Override public Object inner() { return conn.db; }

    private void check() throws SQLException {
        if (closed) throw new SQLException("CLOSED the statement was closed", "HY010");
        conn.check();
    }

    private void needsPrepared() throws SQLException {
        if (sql == null) throw new SQLException("this is a Statement: pass the SQL text", "HY000");
    }

    private void needsPlain() throws SQLException {
        if (sql != null) throw new SQLException("a PreparedStatement runs its own SQL: call it without SQL text", "HY000");
    }

    // ---------------------------------------------------------------- running

    private SqlResult run(String text, List<Object> values) throws SQLException {
        check();
        if (resultSet != null) { resultSet.close(); resultSet = null; }
        updateCount = -1;
        for (int i = 0; i < values.size(); i++)
            if (values.get(i) == UNSET) throw new SQLException("INPUT parameter " + (i + 1) + " is not set", "07001");
        KestroClient db = conn.db;
        try {
            conn.implicitBegin(text);
            SqlResult r = db.sql(text, values);
            if (r.hasRows()) {
                List<Map<String, Object>> rows = r.rows();
                if (maxRows > 0 && rows.size() > maxRows) rows = rows.subList(0, (int) maxRows);
                resultSet = JdbcResultSet.create(self, rows);
            } else {
                updateCount = r.changes();
                if (r.lastInsertId() != null) lastInsertId = r.lastInsertId();
            }
            return r;
        } catch (KestroException e) {
            throw Jdbc.sql(e);
        }
    }

    private ResultSet query(String text, List<Object> values) throws SQLException {
        SqlResult r = run(text, values);
        if (!r.hasRows()) throw new SQLException("INPUT executeQuery needs a statement that returns rows; use executeUpdate", "42000");
        return resultSet;
    }

    private long update(String text, List<Object> values) throws SQLException {
        SqlResult r = run(text, values);
        if (r.hasRows()) { long n = r.rows().size(); updateCount = -1; return n; }   // RETURNING: the rows written
        return updateCount;
    }

    // Statement
    public ResultSet executeQuery(String text) throws SQLException { needsPlain(); return query(text, Collections.emptyList()); }

    public int executeUpdate(String text) throws SQLException { needsPlain(); return (int) Math.min(Integer.MAX_VALUE, update(text, Collections.emptyList())); }

    public int executeUpdate(String text, int autoGeneratedKeys) throws SQLException { return executeUpdate(text); }

    public int executeUpdate(String text, int[] columnIndexes) throws SQLException { return executeUpdate(text); }

    public int executeUpdate(String text, String[] columnNames) throws SQLException { return executeUpdate(text); }

    public long executeLargeUpdate(String text) throws SQLException { needsPlain(); return update(text, Collections.emptyList()); }

    public boolean execute(String text) throws SQLException { needsPlain(); return run(text, Collections.emptyList()).hasRows(); }

    public boolean execute(String text, int autoGeneratedKeys) throws SQLException { return execute(text); }

    public boolean execute(String text, int[] columnIndexes) throws SQLException { return execute(text); }

    public boolean execute(String text, String[] columnNames) throws SQLException { return execute(text); }

    public void addBatch(String text) throws SQLException { check(); needsPlain(); batch.add(text); }

    // PreparedStatement
    public ResultSet executeQuery() throws SQLException { needsPrepared(); return query(sql, new ArrayList<>(params)); }

    public int executeUpdate() throws SQLException { needsPrepared(); return (int) Math.min(Integer.MAX_VALUE, update(sql, new ArrayList<>(params))); }

    public long executeLargeUpdate() throws SQLException { needsPrepared(); return update(sql, new ArrayList<>(params)); }

    public boolean execute() throws SQLException { needsPrepared(); return run(sql, new ArrayList<>(params)).hasRows(); }

    public void addBatch() throws SQLException { check(); needsPrepared(); batch.add(new ArrayList<>(params)); }

    public void clearBatch() throws SQLException { check(); batch.clear(); }

    /** Runs the batch in one transaction (one commit) unless one is already open. */
    public int[] executeBatch() throws SQLException {
        long[] large = executeLargeBatch();
        int[] out = new int[large.length];
        for (int i = 0; i < large.length; i++) out[i] = (int) Math.min(Integer.MAX_VALUE, large[i]);
        return out;
    }

    @SuppressWarnings("unchecked")
    public long[] executeLargeBatch() throws SQLException {
        check();
        List<Object> items = new ArrayList<>(batch);
        batch.clear();
        KestroClient db = conn.db;
        boolean own = false;
        long[] counts = new long[items.size()];
        int done = 0;
        try {
            if (!db.inTransaction() && items.size() > 1) { db.begin(); own = true; }
            for (Object item : items) {
                long n = item instanceof String ? update((String) item, Collections.emptyList()) : update(sql, (List<Object>) item);
                if (resultSet != null) throw new SQLException("INPUT a batch statement returned rows", "42000");
                counts[done++] = n;
            }
            if (own) db.commit();
            return counts;
        } catch (SQLException | KestroException e) {
            if (own && db.inTransaction()) {
                try { db.rollback(); } catch (KestroException r) { e.addSuppressed(r); }
            }
            SQLException cause = e instanceof SQLException ? (SQLException) e : Jdbc.sql((KestroException) e);
            long[] partial = new long[done];
            System.arraycopy(counts, 0, partial, 0, done);
            throw new BatchUpdateException(cause.getMessage(), cause.getSQLState(), cause.getErrorCode(), partial, cause);
        }
    }

    public ResultSet getResultSet() throws SQLException { check(); return resultSet; }

    public int getUpdateCount() throws SQLException { check(); return (int) Math.min(Integer.MAX_VALUE, updateCount); }

    public long getLargeUpdateCount() throws SQLException { check(); return updateCount; }

    public boolean getMoreResults() throws SQLException { return getMoreResults(Statement.CLOSE_CURRENT_RESULT); }

    public boolean getMoreResults(int current) throws SQLException {
        check();
        if (resultSet != null && current != Statement.KEEP_CURRENT_RESULT) resultSet.close();
        resultSet = null;
        updateCount = -1;
        return false;
    }

    /** One column, {@code id}: the id of the row the last INSERT created (no row if none did). */
    public ResultSet getGeneratedKeys() throws SQLException {
        check();
        List<Map<String, Object>> rows = new ArrayList<>();
        if (lastInsertId != null) {
            Map<String, Object> row = new LinkedHashMap<>();
            row.put("id", lastInsertId);
            rows.add(row);
        }
        return JdbcResultSet.create(self, rows, Collections.singletonList("id"));
    }

    // ---------------------------------------------------------------- parameters

    private void set(int index, Object value) throws SQLException {
        check();
        needsPrepared();
        if (index < 1 || index > 65536) throw new SQLException("parameter index " + index + " out of range", "07009");
        while (params.size() < index) params.add(UNSET);
        params.set(index - 1, value);
    }

    public void clearParameters() throws SQLException { check(); params.clear(); }

    public void setNull(int i, int sqlType) throws SQLException { set(i, null); }

    public void setNull(int i, int sqlType, String typeName) throws SQLException { set(i, null); }

    public void setBoolean(int i, boolean v) throws SQLException { set(i, v); }

    public void setByte(int i, byte v) throws SQLException { set(i, (long) v); }

    public void setShort(int i, short v) throws SQLException { set(i, (long) v); }

    public void setInt(int i, int v) throws SQLException { set(i, (long) v); }

    public void setLong(int i, long v) throws SQLException { set(i, v); }

    public void setFloat(int i, float v) throws SQLException { set(i, v); }

    public void setDouble(int i, double v) throws SQLException { set(i, v); }

    public void setBigDecimal(int i, BigDecimal v) throws SQLException { set(i, v); }

    public void setString(int i, String v) throws SQLException { set(i, v); }

    public void setNString(int i, String v) throws SQLException { set(i, v); }

    public void setDate(int i, Date v) throws SQLException { set(i, v); }

    public void setDate(int i, Date v, Calendar cal) throws SQLException { set(i, v); }

    public void setTime(int i, Time v) throws SQLException { set(i, v); }

    public void setTime(int i, Time v, Calendar cal) throws SQLException { set(i, v); }

    public void setTimestamp(int i, Timestamp v) throws SQLException { set(i, v); }

    public void setTimestamp(int i, Timestamp v, Calendar cal) throws SQLException { set(i, v); }

    public void setObject(int i, Object v) throws SQLException { set(i, v); }

    public void setObject(int i, Object v, int targetSqlType) throws SQLException { set(i, v); }

    public void setObject(int i, Object v, int targetSqlType, int scaleOrLength) throws SQLException { set(i, v); }

    /** Unknown until the statement runs (results are self-describing JSON). */
    public ResultSetMetaData getMetaData() throws SQLException { check(); return null; }

    // ---------------------------------------------------------------- settings

    public void close() throws SQLException {
        if (closed) return;
        closed = true;
        if (resultSet != null) resultSet.close();
        resultSet = null;
    }

    public boolean isClosed() { return closed; }

    public Connection getConnection() throws SQLException { check(); return conn.self; }

    public void setMaxRows(int max) throws SQLException { setLargeMaxRows(max); }

    public int getMaxRows() throws SQLException { check(); return (int) Math.min(Integer.MAX_VALUE, maxRows); }

    public void setLargeMaxRows(long max) throws SQLException {
        check();
        if (max < 0) throw new SQLException("maxRows < 0");
        maxRows = max;
    }

    public long getLargeMaxRows() throws SQLException { check(); return maxRows; }

    /** Accepted; the server's --statement-timeout applies. */
    public void setQueryTimeout(int seconds) throws SQLException { check(); queryTimeout = seconds; }

    public int getQueryTimeout() throws SQLException { check(); return queryTimeout; }

    public void setFetchSize(int rows) throws SQLException { check(); fetchSize = rows; }

    public int getFetchSize() throws SQLException { check(); return fetchSize; }

    public void setFetchDirection(int direction) throws SQLException { check(); }

    public int getFetchDirection() throws SQLException { check(); return ResultSet.FETCH_FORWARD; }

    public int getResultSetType() throws SQLException { check(); return ResultSet.TYPE_SCROLL_INSENSITIVE; }

    public int getResultSetConcurrency() throws SQLException { check(); return ResultSet.CONCUR_READ_ONLY; }

    public int getResultSetHoldability() throws SQLException { check(); return ResultSet.HOLD_CURSORS_OVER_COMMIT; }

    public void setMaxFieldSize(int max) throws SQLException { check(); }

    public int getMaxFieldSize() throws SQLException { check(); return 0; }

    public void setEscapeProcessing(boolean enable) throws SQLException { check(); }

    public SQLWarning getWarnings() throws SQLException { check(); return null; }

    public void clearWarnings() throws SQLException { check(); }

    public void setPoolable(boolean on) throws SQLException { check(); poolable = on; }

    public boolean isPoolable() throws SQLException { check(); return poolable; }

    public void closeOnCompletion() throws SQLException { check(); closeOnCompletion = true; }

    public boolean isCloseOnCompletion() throws SQLException { check(); return closeOnCompletion; }

    public void cancel() throws SQLException { throw new SQLFeatureNotSupportedException("cancel"); }
}
