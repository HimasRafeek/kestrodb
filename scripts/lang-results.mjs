// node scripts/lang-results.mjs: gathers bench/lang-compare.mjs results (results/<lang>-<os>.json)
// into results/lang-results.js, which index.html loads (a script, so it works from file://).
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';

const dir = fileURLToPath(new URL('../results/', import.meta.url));
const LANG = {php: 'PHP', python: 'Python'}, OS = {win32: 'Windows', linux: 'Linux', darwin: 'macOS'};
const sets = readdirSync(dir).filter(f => /^(php|python)-[a-z]+\.json$/.test(f)).map(f => JSON.parse(readFileSync(join(dir, f), 'utf8')))
  .sort((a, b) => (a.platform === b.platform ? 0 : a.platform === 'win32' ? -1 : 1) || a.lang.localeCompare(b.lang))
  .map(r => ({
    title: `${LANG[r.lang] ?? r.lang} on ${OS[r.platform] ?? r.platform}`,
    note: `${r.cpu}, ${r.cores} threads${r.os ? ', ' + r.os : ''}, ${new Date(r.date).toISOString().slice(0, 10)}. ${r.writesPerProcess} durable writes and ${r.readsPerProcess.toLocaleString('en-US')} random reads per process, ${r.keys.toLocaleString('en-US')} keys.${r.mysql ? '' : ' MySQL not measured in this set.'}`,
    rows: r.rows.map(row => {
      const out = {workers: row.workers};
      for (const name of ['KestroDB', 'SQLite', 'MySQL']) {
        const v = row[name];
        if (v) out[name] = {writes: Math.round(v.writes), reads: Math.round(v.reads)};
      }
      return out;
    }),
  }));
writeFileSync(join(dir, 'lang-results.js'), '// Generated by scripts/lang-results.mjs from results/<lang>-<os>.json.\nwindow.KESTRO_LANG_RESULTS = ' + JSON.stringify(sets, null, 1) + ';\n');
console.log(`results/lang-results.js: ${sets.map(s => s.title).join(', ')}`);
